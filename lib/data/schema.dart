enum FieldType {
  text,
  multiline,
  number,
  integer,
  date,
  time,
  datetime,
  json,
  boolean,
  select,
  lookup,
}

class FieldSpec {
  const FieldSpec(
    this.key,
    this.label, {
    this.type = FieldType.text,
    this.required = false,
    this.options = const {},
    this.lookupTable,
    this.lookupLabel = 'name',
    this.lookupEquals = const {},
    this.lookupBranchScoped = true,
    this.defaultValue,
    this.hint,
    this.min,
    this.max,
    this.list = false,
    this.width,
    this.generated = false,
  });

  final String key;
  final String label;
  final FieldType type;
  final bool required;
  final Map<String, String> options;
  final String? lookupTable;
  final String lookupLabel;
  final Map<String, Object?> lookupEquals;
  final bool lookupBranchScoped;
  final Object? defaultValue;
  final String? hint;
  final num? min;
  final num? max;
  final bool list;
  final double? width;

  /// True for database-generated columns. They are shown in lists but never
  /// sent in an INSERT or UPDATE.
  final bool generated;
}

class TableSpec {
  const TableSpec({
    required this.table,
    required this.title,
    required this.singular,
    required this.fields,
    this.listColumns = const [],
    this.orderBy,
    this.ascending = true,
    this.branchScoped = true,
    this.primaryKey = 'id',
    this.canCreate = true,
    this.canEdit = true,
    this.canDelete = true,
    this.searchColumns = const [],
    this.description,
    this.defaults = const {},
    this.limit = 500,
  });

  final String table;
  final String title;
  final String singular;
  final List<FieldSpec> fields;
  final List<String> listColumns;
  final String? orderBy;
  final bool ascending;
  final bool branchScoped;
  final String primaryKey;
  final bool canCreate;
  final bool canEdit;
  final bool canDelete;
  final List<String> searchColumns;
  final String? description;
  final Map<String, dynamic> defaults;
  final int limit;

  FieldSpec? field(String key) {
    for (final field in fields) {
      if (field.key == key) return field;
    }
    return null;
  }

  List<String> get effectiveListColumns {
    if (listColumns.isNotEmpty) return listColumns;
    return fields
        .where((field) => field.list)
        .map((field) => field.key)
        .toList();
  }
}

