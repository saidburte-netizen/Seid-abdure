#!/usr/bin/env python3
"""Generate a schema-only SQL fixture from the live Supabase project.

This is a read-only introspection helper. It never writes to the live project
and it never prints the access token. The generated file is intended for a
disposable local Supabase stack so the integration tests can run without
replaying the stale legacy migrations.

Usage:
    SUPABASE_ACCESS_TOKEN=... python3 tool/dump_live_schema.py \
        --project-ref nmrpmypgkljmtnsvmcfn --out supabase/fixtures/live_schema.sql
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from typing import Any, Dict, Iterable, List, Optional

API = "https://api.supabase.com/v1/projects/{ref}/database/query"


def query(token: str, ref: str, sql: str) -> List[Dict[str, Any]]:
    payload = json.dumps({"query": sql}).encode("utf-8")
    request = urllib.request.Request(
        API.format(ref=ref),
        data=payload,
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=180) as response:
            data = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as error:
        detail = error.read().decode("utf-8", "replace")
        raise RuntimeError(f"Management API query failed ({error.code}): {detail}") from error
    if not isinstance(data, list):
        raise RuntimeError(f"Unexpected Management API response: {data!r}")
    return data


def qident(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def qliteral(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def parse_pg_array(value: Any) -> List[Any]:
    if isinstance(value, list):
        return value
    if isinstance(value, str):
        text = value.strip()
        if text.startswith("{") and text.endswith("}"):
            body = text[1:-1].strip()
            if not body:
                return []
            return [
                item.strip().strip('"').replace('\\"', '"')
                for item in body.split(",")
                if item.strip()
            ]
    return []


def sql_type(row: Dict[str, Any]) -> str:
    data_type = (row.get("data_type") or "").lower()
    udt_name = row.get("udt_name") or ""
    udt_schema = row.get("udt_schema") or "public"
    length = row.get("character_maximum_length")
    precision = row.get("numeric_precision")
    scale = row.get("numeric_scale")
    if data_type == "array":
        base = udt_name[1:] if udt_name.startswith("_") else udt_name
        return f"{base}[]"
    if data_type == "user-defined":
        return f"{qident(udt_schema)}.{qident(udt_name)}"
    if data_type == "character varying":
        return f"varchar({length})" if length else "varchar"
    if data_type == "character":
        return f"char({length})" if length else "char"
    if data_type == "numeric":
        if precision and scale is not None:
            return f"numeric({precision},{scale})"
        return "numeric"
    mapping = {
        "timestamp with time zone": "timestamptz",
        "timestamp without time zone": "timestamp",
        "time without time zone": "time",
        "time with time zone": "timetz",
        "double precision": "double precision",
        "real": "real",
        "integer": "integer",
        "bigint": "bigint",
        "smallint": "smallint",
        "boolean": "boolean",
        "jsonb": "jsonb",
        "json": "json",
        "uuid": "uuid",
        "text": "text",
        "date": "date",
        "bytea": "bytea",
        "interval": "interval",
        "inet": "inet",
        "cidr": "cidr",
        "macaddr": "macaddr",
        "tsvector": "tsvector",
        "money": "money",
        "xml": "xml",
    }
    return mapping.get(data_type, data_type or "text")


def column_sql(row: Dict[str, Any]) -> str:
    parts = [qident(row["column_name"]), sql_type(row)]
    if (row.get("is_identity") or "NO") == "YES":
        parts.append("generated by default as identity")
    elif row.get("generation_expression"):
        parts.append(f"generated always as ({row['generation_expression']}) stored")
    elif row.get("column_default") is not None:
        parts.append(f"default {row['column_default']}")
    if (row.get("is_nullable") or "YES") == "NO":
        parts.append("not null")
    return " ".join(parts)


def literal_for(value: Any, column: Dict[str, Any]) -> str:
    if value is None:
        return "null"
    data_type = (column.get("data_type") or "").lower()
    udt_name = column.get("udt_name") or ""
    udt_schema = column.get("udt_schema") or "public"
    if data_type == "array":
        values = parse_pg_array(value)
        if not values:
            return "null"
        base = udt_name[1:] if udt_name.startswith("_") else udt_name
        items = ", ".join(literal_for(item, {"data_type": base, "udt_name": base}) for item in values)
        return f"array[{items}]::{base}[]"
    if data_type == "jsonb":
        return f"{qliteral(json.dumps(value, ensure_ascii=False))}::jsonb"
    if data_type == "json":
        return f"{qliteral(json.dumps(value, ensure_ascii=False))}::json"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if data_type == "user-defined":
        return f"{qliteral(str(value))}::{qident(udt_schema)}.{qident(udt_name)}"
    if data_type in {"integer", "bigint", "smallint", "numeric", "real", "double precision", "money"}:
        return str(value)
    if data_type == "bytea":
        return "null"
    return qliteral(str(value))


def data_inserts(
    token: str,
    ref: str,
    table: str,
    schema: str,
    columns: List[Dict[str, Any]],
    where: str = "",
    only_columns: Optional[List[str]] = None,
) -> List[str]:
    rows = query(token, ref, f"select row_to_json(t) as row from {schema}.{table} t {where}")
    if not rows:
        return []
    by_name = {column["column_name"]: column for column in columns}
    names = [
        column["column_name"]
        for column in columns
        if only_columns is None or column["column_name"] in only_columns
    ]
    statements: List[str] = []
    for item in rows:
        row = item.get("row")
        if isinstance(row, str):
            row = json.loads(row)
        if not isinstance(row, dict):
            continue
        values = []
        for name in names:
            if name not in row:
                continue
            values.append(literal_for(row[name], by_name[name]))
        columns_sql = ", ".join(qident(name) for name in names if name in row)
        statements.append(
            f"insert into {schema}.{table} ({columns_sql}) values ({', '.join(values)}) "
            "on conflict do nothing;"
        )
    return statements


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--project-ref", default=os.environ.get("SUPABASE_PROJECT_REF", ""))
    parser.add_argument("--out", default="supabase/fixtures/live_schema.sql")
    args = parser.parse_args()
    token = os.environ.get("SUPABASE_ACCESS_TOKEN", "").strip()
    if not token:
        print("SUPABASE_ACCESS_TOKEN is required", file=sys.stderr)
        return 2
    if not args.project_ref:
        print("--project-ref or SUPABASE_PROJECT_REF is required", file=sys.stderr)
        return 2
    ref = args.project_ref

    print("Reading extensions, enums and columns...", file=sys.stderr)
    extensions = query(
        token,
        ref,
        """
        select e.extname, n.nspname as schema_name
        from pg_extension e
        join pg_namespace n on n.oid = e.extnamespace
        where e.extname <> 'plpgsql'
        order by e.extname
        """,
    )
    enums = query(
        token,
        ref,
        """
        select n.nspname as schema_name, t.typname, e.enumlabel
        from pg_type t
        join pg_enum e on e.enumtypid = t.oid
        join pg_namespace n on n.oid = t.typnamespace
        where n.nspname in ('public')
        order by t.typname, e.enumsortorder
        """,
    )
    columns = query(
        token,
        ref,
        """
        select table_schema, table_name, column_name, ordinal_position, data_type,
               udt_schema, udt_name, character_maximum_length, numeric_precision,
               numeric_scale, is_nullable, column_default, is_identity,
               generation_expression
        from information_schema.columns
        where table_schema in ('public', 'storage')
        order by table_schema, table_name, ordinal_position
        """,
    )
    sequences = query(
        token,
        ref,
        """
        select sequence_schema, sequence_name
        from information_schema.sequences
        where sequence_schema = 'public'
        order by sequence_name
        """,
    )
    base_tables = {
        row["table_name"]
        for row in query(
            token,
            ref,
            """
            select c.relname as table_name
            from pg_class c
            join pg_namespace n on n.oid = c.relnamespace
            where n.nspname = 'public' and c.relkind in ('r', 'p')
            """,
        )
    }
    constraints = query(
        token,
        ref,
        """
        select n.nspname as schema_name, c.relname as table_name,
               con.conname, con.contype, pg_get_constraintdef(con.oid) as definition
        from pg_constraint con
        join pg_class c on c.oid = con.conrelid
        join pg_namespace n on n.oid = c.relnamespace
        where n.nspname in ('public', 'storage')
        order by n.nspname, c.relname, con.conname
        """,
    )
    indexes = query(
        token,
        ref,
        """
        select schemaname, tablename, indexname, indexdef
        from pg_indexes
        where schemaname in ('public', 'storage')
        order by schemaname, tablename, indexname
        """,
    )
    views = query(
        token,
        ref,
        """
        select schemaname, viewname, definition
        from pg_views
        where schemaname = 'public'
        order by viewname
        """,
    )
    functions = query(
        token,
        ref,
        """
        select n.nspname as schema_name, p.proname,
               pg_get_functiondef(p.oid) as definition
        from pg_proc p
        join pg_namespace n on n.oid = p.pronamespace
        where n.nspname = 'public'
          and p.prokind = 'f'
          and p.oid not in (select objid from pg_depend where deptype = 'e')
        order by p.proname
        """,
    )
    triggers = query(
        token,
        ref,
        """
        select n.nspname as schema_name, c.relname as table_name,
               t.tgname, pg_get_triggerdef(t.oid) as definition
        from pg_trigger t
        join pg_class c on c.oid = t.tgrelid
        join pg_namespace n on n.oid = c.relnamespace
        where n.nspname in ('public', 'auth')
          and not t.tgisinternal
        order by n.nspname, c.relname, t.tgname
        """,
    )
    auth_trigger_functions = query(
        token,
        ref,
        """
        select distinct p.oid::bigint as oid, n.nspname as schema_name, p.proname,
               pg_get_functiondef(p.oid) as definition
        from pg_trigger t
        join pg_class c on c.oid = t.tgrelid
        join pg_namespace n on n.oid = c.relnamespace
        join pg_proc p on p.oid = t.tgfoid
        join pg_namespace pn on pn.oid = p.pronamespace
        where n.nspname = 'auth'
          and c.relname = 'users'
          and not t.tgisinternal
        order by p.proname
        """,
    )
    rls = query(
        token,
        ref,
        """
        select n.nspname as schema_name, c.relname as table_name,
               c.relrowsecurity, c.relforcerowsecurity
        from pg_class c
        join pg_namespace n on n.oid = c.relnamespace
        where n.nspname = 'public' and c.relkind = 'r'
        order by c.relname
        """,
    )
    policies = query(
        token,
        ref,
        """
        select schemaname, tablename, policyname, permissive, roles, cmd,
               qual, with_check
        from pg_policies
        where schemaname in ('public', 'storage')
        order by schemaname, tablename, policyname
        """,
    )

    print("Reading catalog rows...", file=sys.stderr)
    data_tables = ["roles", "permissions", "role_permissions", "app_settings"]
    data_columns: Dict[str, List[Dict[str, Any]]] = {}
    for table in data_tables:
        data_columns[table] = [row for row in columns if row["table_schema"] == "public" and row["table_name"] == table]
    storage_columns = [row for row in columns if row["table_schema"] == "storage" and row["table_name"] == "buckets"]

    out: List[str] = []
    out.append("-- Generated read-only from the live Supabase project.")
    out.append("-- Schema-only fixture for disposable local integration tests.")
    out.append("-- Do not run this against the live project.")
    out.append("set check_function_bodies = false;")
    out.append("set client_min_messages = warning;")
    out.append("")
    for extension in extensions:
        out.append(
            f"create extension if not exists {qident(extension['extname'])} "
            f"with schema {qident(extension['schema_name'])};"
        )
    out.append("")

    enum_groups: Dict[tuple, List[str]] = {}
    for row in enums:
        enum_groups.setdefault((row["schema_name"], row["typname"]), []).append(row["enumlabel"])
    for (schema_name, typname), labels in enum_groups.items():
        out.append(
            f"do $$ begin create type {qident(schema_name)}.{qident(typname)} as enum "
            f"({', '.join(qliteral(label) for label in labels)}); "
            "exception when duplicate_object then null; end $$;"
        )
    for row in sequences:
        out.append(
            f"create sequence if not exists {qident(row['sequence_schema'])}.{qident(row['sequence_name'])};"
        )
    out.append("")

    column_groups: Dict[tuple, List[Dict[str, Any]]] = {}
    for row in columns:
        if row["table_schema"] != "public":
            continue
        if row["table_name"] not in base_tables:
            continue
        column_groups.setdefault((row["table_schema"], row["table_name"]), []).append(row)
    for (schema_name, table_name), rows in sorted(column_groups.items()):
        out.append(f"create table if not exists {qident(schema_name)}.{qident(table_name)} (")
        out.append(",\n".join("  " + column_sql(row) for row in rows))
        out.append(");")
    out.append("")

    constraint_names = {(row["schema_name"], row["table_name"], row["conname"]) for row in constraints}
    for row in constraints:
        if row["schema_name"] != "public":
            continue
        out.append(
            f"alter table {qident(row['schema_name'])}.{qident(row['table_name'])} "
            f"add constraint {qident(row['conname'])} {row['definition']};"
        )
    out.append("")

    for row in indexes:
        if row["schemaname"] != "public":
            continue
        if (row["schemaname"], row["tablename"], row["indexname"]) in constraint_names:
            continue
        if row["indexname"].endswith("_pkey") or row["indexname"].endswith("_key"):
            continue
        out.append(row["indexdef"].rstrip(";") + ";")
    out.append("")

    for row in functions:
        out.append(row["definition"].rstrip(";") + ";")
    out.append("")
    for row in auth_trigger_functions:
        out.append(row["definition"].rstrip(";") + ";")
    out.append("")

    for row in views:
        out.append(
            f"create or replace view public.{qident(row['viewname'])} as\n"
            f"{row['definition'].rstrip(';')};"
        )
    out.append("")

    for row in triggers:
        out.append(row["definition"].rstrip(";") + ";")
    out.append("")

    for row in rls:
        out.append(f"alter table public.{qident(row['table_name'])} enable row level security;")
        if row.get("relforcerowsecurity"):
            out.append(f"alter table public.{qident(row['table_name'])} force row level security;")
    out.append("")

    for row in policies:
        roles = parse_pg_array(row.get("roles"))
        role_sql = ", ".join(str(role) for role in roles) if roles else "public"
        permissive = (row.get("permissive") or "PERMISSIVE").lower()
        cmd = (row.get("cmd") or "ALL").lower()
        out.append(
            f"drop policy if exists {qident(row['policyname'])} on "
            f"{qident(row['schemaname'])}.{qident(row['tablename'])};"
        )
        sql = (
            f"create policy {qident(row['policyname'])} on {qident(row['schemaname'])}.{qident(row['tablename'])} "
            f"as {permissive} for {cmd} to {role_sql}"
        )
        if row.get("qual"):
            sql += f" using ({row['qual']})"
        if row.get("with_check"):
            sql += f" with check ({row['with_check']})"
        out.append(sql + ";")
    out.append("")

    out.append("grant usage on schema public to anon, authenticated;")
    out.append("grant all on all tables in schema public to anon, authenticated;")
    out.append("grant all on all sequences in schema public to anon, authenticated;")
    out.append("grant execute on all functions in schema public to anon, authenticated;")
    out.append("-- Local storage grants. The hosted project already has the equivalent")
    out.append("-- grants; these keep the disposable local stack faithful to it.")
    out.append("grant usage on schema storage to anon, authenticated;")
    out.append("grant select on storage.buckets to anon, authenticated;")
    out.append("grant select, insert, update, delete on storage.objects to anon, authenticated;")
    out.append("")

    for table in data_tables:
        out.extend(data_inserts(token, ref, table, "public", data_columns[table]))
    if storage_columns:
        out.extend(
            data_inserts(
                token,
                ref,
                "buckets",
                "storage",
                storage_columns,
                only_columns=["id", "name", "public", "file_size_limit", "allowed_mime_types"],
            )
        )
    out.append("")

    out.append("-- End of generated schema fixture.")
    text = "\n".join(out) + "\n"
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(
        f"Wrote {args.out}: {len(columns)} columns, {len(constraints)} constraints, "
        f"{len(functions)} functions, {len(views)} views, {len(triggers)} triggers, "
        f"{len(policies)} policies, {len(text.splitlines())} lines.",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
